/**
 * Experiment 1 (free part): the gap ledger and what every free finder reports on each model as
 * it stands.
 *
 *   bun ledger.ts --models viewer=~/workspace/documentation_robotics_viewer,cs=~/workspace/context-studio [--no-code]
 *
 * Writes data/ledger-report.md, data/<model>/ledger.json and data/<model>/findings.json.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { claimNodes, coverage } from "./code-graph.js";
import { ledgerSummary } from "./ledger-core.js";
import {
  dataDir,
  FINDER_NAMES,
  num,
  parseFlags,
  runFinders,
  setup
} from "./run.js";

const flags = parseFlags(process.argv.slice(2));
const { catalog, models } = await setup(flags);

const out: string[] = [];
const say = (s = "") => out.push(s);
const cross = catalog.triples.filter(
  (t) => t.source.split(".")[0] !== t.destination.split(".")[0]
);

say("# Gap ledger and free-finder baseline");
say();
say(
  `Spec ${catalog.specVersion}: ${catalog.nodeTypes.length} node types, ${num(catalog.triples.length)} relationship types, ${cross.length} between layers, of which a mapped CBM edge can produce ${cross.filter((t) => catalog.reachable.has(t.id)).length}. Generated by \`ledger.ts\`; no model calls.`
);
say();
say("## Models");
say();
say(
  "| Model | Commit | Elements | Relationships | Layers | No relationship | Linked pairs, both populated | Empty | Thin | Cross-layer types instantiable | Unused | Low | Open and reachable | Open, no edge route | Unwired entries per element |"
);
say(
  "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"
);
const summaries = models.map((m) =>
  ledgerSummary(m.model, m.idx, m.ledger, catalog)
);
for (const s of summaries) {
  say(
    `| ${s.model} | ${s.commit} | ${num(s.elements)} | ${num(s.relationships)} | ${s.layersPopulated} | ${num(s.noRelationship)} | ${s.pairsBothPopulated} | ${s.pairsEmpty} | ${s.pairsThin} | ${s.crossTypesInstantiable} | ${s.crossTypesUnused} | ${s.crossTypesLow} | ${s.openReachable} | ${s.openUnreachable} | ${s.unwiredPerElement.toFixed(1)} |`
  );
}
say();
say(
  "Unused: no relationship of the type. Low: under a fifth of the source type's elements have one. Open: unused or low."
);

say();
say("## What the free finders report on each model as it stands");
say();
say(
  "Findings, not validated: this is the volume a reviewer or a model would face, and the baseline the seeded-gap runs subtract."
);
say();
say(`| Model | ${FINDER_NAMES.join(" | ")} |`);
say(`| --- | ${FINDER_NAMES.map(() => "---").join(" | ")} |`);
const codeRows: string[] = [];
for (const m of models) {
  const fleet = models.filter((o) => o !== m);
  const run = runFinders(m.model, catalog, fleet, m.graph);
  say(
    `| ${m.model.name} | ${FINDER_NAMES.map((f) => (run.findings.has(f) ? num(run.findings.get(f)!.length) : "no index")).join(" | ")} |`
  );
  const dir = dataDir(m.model.name);
  writeFileSync(
    path.join(dir, "ledger.json"),
    `${JSON.stringify({ summary: summaries[models.indexOf(m)], pairs: m.ledger.pairs, types: m.ledger.types.map((t) => ({ ...t, triple: t.triple.id })) }, null, 2)}\n`
  );
  writeFileSync(
    path.join(dir, "findings.json"),
    `${JSON.stringify(Object.fromEntries(run.findings), null, 2)}\n`
  );
  if (m.graph) {
    const c = coverage(m.model, m.graph, claimNodes(m.model, m.graph));
    codeRows.push(
      `| ${m.model.name} | ${num(c.nodes)} | ${num(c.edges)} | ${num(c.elementsLocated)} | ${num(c.elementsWithIndexedFile)} | ${num(c.elementsClaimingNodes)} |`
    );
  } else {
    codeRows.push(`| ${m.model.name} | no index for ${m.model.root} | | | | |`);
  }
}
say();
say("## What the code index sees of each model");
say();
say(
  "| Model | Index nodes | Edges loaded | Elements with a source reference | In an indexed file | Tied to index nodes |"
);
say("| --- | --- | --- | --- | --- | --- |");
for (const row of codeRows) say(row);

for (const m of models) {
  say();
  say(`## ${m.model.name}: layer pairs`);
  say();
  say(
    "| Pair | Elements | State | Catalog types | Instantiable | Used | Relationships | Reachable |"
  );
  say("| --- | --- | --- | --- | --- | --- | --- | --- |");
  for (const p of m.ledger.pairs.filter((p) => p.state !== "layer-absent")) {
    say(
      `| ${p.pair} | ${p.elements[0]} / ${p.elements[1]} | ${p.state} | ${p.catalogTypes} | ${p.instantiable} | ${p.used} | ${num(p.relationships)} | ${p.reachable} |`
    );
  }
  const absent = catalog.layers.filter((l) => !m.idx.byLayer.has(l));
  if (absent.length) {
    say();
    say(`Absent layers: ${absent.join(", ")}.`);
  }
}

const file = path.join(dataDir(), "ledger-report.md");
writeFileSync(file, `${out.join("\n")}\n`);
console.log(out.slice(0, 40).join("\n"));
console.log(`\nWrote ${file}`);

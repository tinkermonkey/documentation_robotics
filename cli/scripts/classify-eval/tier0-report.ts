/**
 * How well the cbm analyzer's Tier-0 rules agree with the gold labels. No model calls.
 *
 *   bun tier0-report.ts [--corpus fastapi] [--out data/tier0-report.md]
 *
 * Per rule and corpus: cards it fired on; for a deciding rule, how many decisions match gold
 * (layer and type); for a narrowing rule, how many golds are still reachable (gold is 'none'
 * or one of the candidates). Needs facts.jsonl per corpus (bun facts.ts).
 */
import path from "node:path";
import { writeFileSync } from "node:fs";
import { corpusDir, flagStr, parseFlags, readJsonl } from "./lib/io.js";
import { harnessDir } from "./lib/env.js";
import { loadFacts, loadTier0Rules, tier0For } from "./lib/tier0.js";
import type { Card, Gold } from "./lib/types.js";

const CORPORA = ["dr-cli", "fastapi", "petclinic"];

function main() {
  const flags = parseFlags(process.argv.slice(2));
  const only = flagStr(flags, "corpus");
  const out = flagStr(flags, "out") ?? path.join(harnessDir(), "data", "tier0-report.md");
  const rules = loadTier0Rules();
  const corpora = only ? [only] : CORPORA;

  type Row = { fired: number; ok: number; misses: string[] };
  const byRule = new Map<string, Map<string, Row>>();
  const totals = new Map<string, { cards: number; decided: number; decidedOk: number; narrowed: number; narrowedOk: number }>();
  for (const corpus of corpora) {
    const dir = corpusDir(corpus);
    const cards = new Map(readJsonl<Card>(path.join(dir, "cards.jsonl")).map((c) => [c.id, c]));
    const facts = loadFacts(corpus);
    const gold = readJsonl<Gold>(path.join(dir, "gold.jsonl"));
    const t = { cards: gold.length, decided: 0, decidedOk: 0, narrowed: 0, narrowedOk: 0 };
    for (const g of gold) {
      const card = cards.get(g.card_id);
      if (!card) continue;
      const o = tier0For(card, facts.get(card.id), rules);
      if (!o) continue;
      const goldId = g.layer === "none" ? "none" : `${g.layer}.${g.element_type ?? "-"}`;
      let ok: boolean;
      if (o.kind === "decide") {
        ok = o.layer === g.layer && (o.layer === "none" || o.type === g.element_type);
        t.decided++;
        if (ok) t.decidedOk++;
      } else {
        ok = g.layer === "none" || o.candidates.some((c) => c.layer === g.layer && (c.type === null || c.type === g.element_type));
        t.narrowed++;
        if (ok) t.narrowedOk++;
      }
      if (!byRule.has(o.rule)) byRule.set(o.rule, new Map());
      const r = byRule.get(o.rule)!.get(corpus) ?? { fired: 0, ok: 0, misses: [] };
      r.fired++;
      if (ok) r.ok++;
      else r.misses.push(`${card.label} ${card.name} (gold ${goldId})`);
      byRule.get(o.rule)!.set(corpus, r);
    }
    totals.set(corpus, t);
  }

  const pct = (a: number, b: number) => (b ? `${((100 * a) / b).toFixed(1)}%` : "n/a");
  const lines: string[] = ["# Tier-0 rules against gold", "", `Rules: spec/dist/analyzers/cbm.json (${rules.length} Tier-0 rules). Generated by tier0-report.ts.`, ""];
  lines.push("| corpus | gold cards | decided by a rule | decisions matching gold | narrowed | gold still reachable |", "|---|---|---|---|---|---|");
  for (const [c, t] of totals) lines.push(`| ${c} | ${t.cards} | ${t.decided} (${pct(t.decided, t.cards)}) | ${t.decidedOk} (${pct(t.decidedOk, t.decided)}) | ${t.narrowed} (${pct(t.narrowed, t.cards)}) | ${t.narrowedOk} (${pct(t.narrowedOk, t.narrowed)}) |`);
  lines.push("", "| rule | outcome | " + corpora.join(" | ") + " |", "|---|---|" + corpora.map(() => "---").join("|") + "|");
  for (const rule of rules) {
    const m = byRule.get(rule.name);
    const cells = corpora.map((c) => {
      const r = m?.get(c);
      return r ? `${r.ok}/${r.fired}` : "-";
    });
    lines.push(`| ${rule.name} | ${rule.decide ? "decide" : "narrow"} | ${cells.join(" | ")} |`);
  }
  lines.push("", "Cells are matching/fired (decide: decision equals gold; narrow: gold is none or among the candidates).", "", "## Misses", "");
  for (const [rule, m] of byRule) for (const [c, r] of m) if (r.misses.length) lines.push(`- **${rule}** (${c}): ${r.misses.join("; ")}`);
  const text = lines.join("\n") + "\n";
  writeFileSync(out, text);
  console.log(text);
}

main();
